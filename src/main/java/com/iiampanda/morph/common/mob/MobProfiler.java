package com.iiampanda.morph.common.mob;

import com.iiampanda.morph.api.mob.trait.*;
import com.iiampanda.morph.api.mob.trait.ability.*;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.EntityTypeTags;
import net.minecraft.world.damagesource.DamageSource;
import net.minecraft.world.effect.MobEffectInstance;
import net.minecraft.world.effect.MobEffects;
import net.minecraft.world.entity.*;
import net.minecraft.world.entity.ai.attributes.AttributeInstance;
import net.minecraft.world.entity.ai.attributes.Attributes;
import net.minecraft.world.entity.ai.control.FlyingMoveControl;
import net.minecraft.world.entity.ai.navigation.FlyingPathNavigation;
import net.minecraft.world.entity.ai.navigation.WallClimberNavigation;
import net.minecraft.world.entity.animal.FlyingAnimal;
import net.minecraft.world.entity.boss.enderdragon.EnderDragon;
import net.minecraft.world.entity.monster.AbstractSkeleton;
import net.minecraft.world.entity.monster.Enemy;
import net.minecraft.world.entity.monster.Zombie;
import net.minecraft.world.entity.monster.Blaze;
import net.minecraft.world.entity.monster.Vex;
import net.minecraft.world.entity.animal.WaterAnimal;
import net.minecraft.world.entity.animal.Dolphin;
import net.minecraft.world.entity.monster.Spider;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.Locale;
import java.util.Set;

/**
 * Looks at a live instance of any mob (vanilla or modded) and works out which traits and abilities it should grant.
 * The result is written to the mob's config file so players can edit it afterwards.
 */
public final class MobProfiler
{
    private static final String[] VARIANT_HINTS = {"variant", "type", "colo", "skin", "texture", "size", "kind", "pattern", "model", "style", "breed", "species", "form", "coat", "marking"};

    private MobProfiler() {}

    public static MobProfile detect(LivingEntity e)
    {
        MobProfile profile = new MobProfile();
        ResourceLocation id = BuiltInRegistries.ENTITY_TYPE.getKey(e.getType());
        profile.forEntity = id.toString();
        profile.autoDetected = true;
        profile.comment = "Generated by Morph by inspecting this mob. Edit freely; Morph will not overwrite this file. Delete it to regenerate. "
                + "Bosses get one special move (right click while morphed); change or replace the abilitySpecial... entry. Trait types: " + String.join(", ", TraitHandler.types());
        profile.variantKeys = detectVariantKeys(e);
        if(isPart(e))
        {
            profile.allowMorph = false;
        }

        ArrayList<Trait<?>> traits = new ArrayList<>();
        Mob mob = e instanceof Mob m ? m : null;

        // --- flying ---
        boolean flier = e instanceof FlyingAnimal || e instanceof FlyingMob || e instanceof EnderDragon || e instanceof Vex || e instanceof Blaze
                || (mob != null && (mob.getMoveControl() instanceof FlyingMoveControl || mob.getNavigation() instanceof FlyingPathNavigation
                || nameHas(mob.getMoveControl(), "flight", "flying", "ethereal") || nameHas(mob.getNavigation(), "flying", "flight")))
                || e.getAttribute(Attributes.FLYING_SPEED) != null && e.getAttributeBaseValue(Attributes.FLYING_SPEED) > 0D
                || e.getType() == EntityType.BAT;
        if(flier)
        {
            double size = e.getBbWidth() * e.getBbHeight();
            if(size < 1.6D)
            {
                FlightFlapAbility flap = new FlightFlapAbility();
                flap.slowdownInWater = true;
                traits.add(flap);
                FlyAbility fly = new FlyAbility();
                fly.upgradeFor = flap.type;
                fly.slowdownInWater = true;
                traits.add(fly);
            }
            else
            {
                FlyAbility fly = new FlyAbility();
                fly.slowdownInWater = true;
                traits.add(fly);
            }
        }

        // --- wall climbing ---
        if(e instanceof Spider || (mob != null && mob.getNavigation() instanceof WallClimberNavigation))
        {
            traits.add(new ClimbAbility());
        }

        // --- water ---
        boolean modded = !"minecraft".equals(id.getNamespace());
        net.minecraft.world.entity.MobCategory cat = e.getType().getCategory();
        boolean waterCat = cat == net.minecraft.world.entity.MobCategory.WATER_CREATURE || cat == net.minecraft.world.entity.MobCategory.WATER_AMBIENT || cat == net.minecraft.world.entity.MobCategory.UNDERGROUND_WATER_CREATURE;
        boolean semiNav = modded && (nameHas(mob != null ? mob.getNavigation() : null, "semiaquatic", "swimmerjump", "amphib"));
        boolean strictWater = e instanceof WaterAnimal || false || (modded && (waterCat || (mob != null && mob.getNavigation() instanceof net.minecraft.world.entity.ai.navigation.WaterBoundPathNavigation)));
        boolean waterAnimal = strictWater && !semiNav;
        boolean semiAquatic = modded && !waterAnimal && (semiNav || nameHas(mob != null ? mob.getMoveControl() : null, "aquatic", "swim"));
        boolean breathesWater = e.canBreatheUnderwater() || (modded && modBreathesUnderwater(e));
        if(waterAnimal)
        {
            SwimmerTrait swim = new SwimmerTrait();
            swim.swimMultiplier = e instanceof Dolphin ? 4D : 2D;
            swim.landMultiplier = breathesWater ? 0.025D : 0.1D;
            traits.add(swim);
        }
        else if(semiAquatic)
        {
            SwimmerTrait swim = new SwimmerTrait();
            swim.swimMultiplier = 2D;
            swim.landMultiplier = 1D;
            traits.add(swim);
        }
        if(breathesWater)
        {
            WaterBreatherTrait wb = new WaterBreatherTrait();
            wb.suffocatesOnLand = waterAnimal;
            if(waterAnimal)
            {
                wb.nightVisionInWater = true;
            }
            traits.add(wb);
            if(e instanceof Dolphin)
            {
                traits.add(new DolphinLeapTrait());
                traits.add(new DolphinsGraceTrait());
            }
        }
        else if(waterAnimal)
        {
            traits.add(new MoistSkinTrait());
        }

        // --- immunities ---
        if(e.fireImmune())
        {
            traits.add(new FireImmunityTrait());
        }
        if(safeInvulnerable(e, e.damageSources().explosion(null, null)))
        {
            traits.add(new ExplosiveImmunityTrait());
        }
        if(safeInvulnerable(e, e.damageSources().magic()))
        {
            traits.add(new MagicImmunityTrait());
        }
        for(net.minecraft.core.Holder<net.minecraft.world.effect.MobEffect> holder : java.util.List.of(MobEffects.POISON, MobEffects.WITHER))
        {
            try
            {
                if(!e.canBeAffected(new MobEffectInstance(holder)))
                {
                    EffectResistanceTrait resist = new EffectResistanceTrait();
                    resist.effectId = BuiltInRegistries.MOB_EFFECT.getKey(holder.value()).toString();
                    traits.add(resist);
                }
            }
            catch(Throwable ignored) {}
        }
        for(String dmg : new String[]{"drown", "cactus", "freeze"})
        {
            // drowning/freezing immunity usually mirrors the water breathing / freeze immune tags
            if(dmg.equals("freeze") && e.getType().is(EntityTypeTags.FREEZE_IMMUNE_ENTITY_TYPES))
            {
                DamageSourceImmunityTrait t = new DamageSourceImmunityTrait();
                t.damageType = "freeze";
                traits.add(t);
            }
        }

        // --- mob nature ---
        if(e instanceof Enemy)
        {
            traits.add(new HostileTrait());
        }
        if(e.getType().is(EntityTypeTags.UNDEAD))
        {
            traits.add(new UndeadTrait());
            if(e instanceof Zombie || e instanceof AbstractSkeleton)
            {
                traits.add(new SunburnTrait());
            }
        }

        // --- movement attributes ---
        AttributeInstance step = e.getAttribute(Attributes.STEP_HEIGHT);
        if(step != null && step.getBaseValue() > 0.61D)
        {
            StepHeightTrait st = new StepHeightTrait();
            st.amount = round(step.getBaseValue());
            traits.add(st);
        }
        AttributeInstance safe = e.getAttribute(Attributes.SAFE_FALL_DISTANCE);
        AttributeInstance fallMult = e.getAttribute(Attributes.FALL_DAMAGE_MULTIPLIER);
        if((safe != null && safe.getBaseValue() >= 8D) || (fallMult != null && fallMult.getBaseValue() <= 0.01D))
        {
            traits.add(new FallNegateTrait());
        }
        AttributeInstance gravity = e.getAttribute(Attributes.GRAVITY);
        if(!flier && gravity != null && gravity.getBaseValue() < 0.07D && gravity.getBaseValue() > 0D)
        {
            SlowFallAbility sf = new SlowFallAbility();
            sf.velocityMultiplier = Math.max(0.2D, gravity.getBaseValue() / 0.08D);
            traits.add(sf);
        }

        // --- newer abilities ---
        net.minecraft.world.entity.EntityType<?> et = e.getType();
        if(BuiltInRegistries.ENTITY_TYPE.getKey(e.getType()).getPath().equals("armadillo"))
        {
            // armour plating: shrugs off fire and explosions
            if(traits.stream().noneMatch(tr -> tr instanceof FireImmunityTrait))
            {
                traits.add(new FireImmunityTrait());
            }
            if(traits.stream().noneMatch(tr -> tr instanceof ExplosiveImmunityTrait))
            {
                traits.add(new ExplosiveImmunityTrait());
            }
        }
        if(BuiltInRegistries.ENTITY_TYPE.getKey(e.getType()).getPath().equals("frog"))
        {
            traits.add(new SpecialFrogHopAbility());
        }
        if(et == EntityType.WARDEN)
        {
            traits.add(new DarknessAuraTrait());
        }
        if(et == EntityType.CAT || et == EntityType.OCELOT || et == EntityType.BAT || et == EntityType.SPIDER || et == EntityType.CAVE_SPIDER
                || et == EntityType.PHANTOM || et == EntityType.WARDEN)
        {
            traits.add(new FullBrightTrait());
        }
        if(e instanceof net.minecraft.world.entity.monster.Blaze || e instanceof net.minecraft.world.entity.monster.MagmaCube || et == EntityType.GLOW_SQUID)
        {
            EmissiveTrait glow = new EmissiveTrait();
            glow.lightLevel = e instanceof net.minecraft.world.entity.monster.Blaze ? 12 : 8;
            traits.add(glow);
        }
        if(e instanceof net.minecraft.world.entity.Shearable)
        {
            ShearableAbility shear = new ShearableAbility();
            shear.dropItem = e instanceof net.minecraft.world.entity.animal.MushroomCow ? "minecraft:red_mushroom" : e instanceof net.minecraft.world.entity.animal.SnowGolem ? "minecraft:carved_pumpkin" : "minecraft:white_wool";
            if(e instanceof net.minecraft.world.entity.animal.SnowGolem) { shear.minCount = 1; shear.maxCount = 1; }
            traits.add(shear);
        }
        if(e instanceof net.minecraft.world.entity.animal.Bucketable bucketable)
        {
            try
            {
                CanBucketAbility bucket = new CanBucketAbility();
                bucket.bucketItem = BuiltInRegistries.ITEM.getKey(bucketable.getBucketItemStack().getItem()).toString();
                traits.add(bucket);
            }
            catch(Throwable ignored) {}
        }

        // --- riding ---
        if(isSaddleable(e))
        {
            RideableAbility ride = new RideableAbility();
            ride.requiresSaddle = false;
            traits.add(ride);
        }

        // --- boss / mini boss special move ---
        SpecialAbility<?> special = SpecialAbilities.defaultFor(e);
        if(special != null)
        {
            traits.add(special);
        }
        profile.specialsHandled = true;

        profile.traits = new ArrayList<>(traits);
        return profile;
    }

    /** Only mobs a player can actually put a saddle on (llamas take carpets, not saddles). */
    public static boolean isSaddleable(LivingEntity e)
    {
        return e instanceof Saddleable && !(e instanceof net.minecraft.world.entity.animal.horse.Llama);
    }


    /** Brings a profile written by an older build up to date (once; edit the file afterwards and Morph leaves it alone). @return true if the file needs saving */
    public static boolean migrate(MobProfile p, LivingEntity sample)
    {
        var id = BuiltInRegistries.ENTITY_TYPE.getKey(sample.getType());
        boolean changed = false;
        // profiles written by older builds may call mobs rideable that are not (e.g. the Warden)
        if(!isRideable(sample) && (p.autoDetected != null && p.autoDetected || "minecraft".equals(id.getNamespace())))
        {
            changed |= p.traits.removeIf(tr -> tr instanceof RideableAbility);
        }
        if(isPart(sample) && p.autoDetected != null && p.autoDetected && p.allowMorph == null)
        {
            p.allowMorph = false;
            changed = true;
        }
        if(!"minecraft".equals(id.getNamespace()) && p.autoDetected != null && p.autoDetected)
        {
            // profiles Morph wrote for modded mobs before it could read their flight / swimming / breathing logic
            changed |= addTraits(p, detect(sample).traits);
        }
        changed |= addMissing(p, sample);
        return changed;
    }

    private static boolean addTraits(MobProfile existing, java.util.List<Trait<?>> wanted)
    {
        boolean changed = false;
        for(Trait<?> t : wanted)
        {
            boolean has = false;
            for(Trait<?> o : existing.traits)
            {
                has |= o.type.equals(t.type);
            }
            if(!has)
            {
                existing.traits.add(t);
                changed = true;
            }
        }
        return changed;
    }

    public static boolean isRideable(LivingEntity e) { return isSaddleable(e); }

    private static boolean addMissing(MobProfile existing, LivingEntity sample)
    {
        boolean changed = addSpecialDefaults(existing, sample);
        boolean dolphin = sample instanceof Dolphin;
        if(dolphin || BuiltInRegistries.ENTITY_TYPE.getKey(sample.getType()).getPath().equals("armadillo") || BuiltInRegistries.ENTITY_TYPE.getKey(sample.getType()).getPath().equals("frog"))
        {
            changed |= addTraits(existing, detect(sample).traits);
            if(dolphin)
            {
                changed |= existing.traits.removeIf(tr -> tr instanceof MoistSkinTrait);
                for(Trait<?> t : existing.traits)
                {
                    if(t instanceof WaterBreatherTrait wb && (wb.suffocatesOnLand == null || !wb.suffocatesOnLand || wb.nightVisionInWater == null || !wb.nightVisionInWater))
                    {
                        wb.suffocatesOnLand = true;
                        wb.nightVisionInWater = true;
                        changed = true;
                    }
                }
            }
        }
        return changed;
    }

    /** Newer vanilla mobs and special moves added after a profile was first written. */
    private static boolean addSpecialDefaults(MobProfile existing, LivingEntity sample)
    {
        var id = BuiltInRegistries.ENTITY_TYPE.getKey(sample.getType());
        if("minecraft".equals(id.getNamespace()) && id.getPath().equals("ghast"))
        {
            for(Trait<?> t : existing.traits)
            {
                if(t instanceof SpecialProjectileAbility sp && "minecraft:entity.ghast.shoot".equals(sp.sound))
                {
                    sp.sound = "event:1015,event:1016";
                    return true;
                }
            }
        }
        if("minecraft".equals(id.getNamespace()) && (id.getPath().equals("ghast") || id.getPath().equals("armadillo")) && !SpecialAbilities.hasSpecial(existing))
        {
            SpecialAbility<?> def = SpecialAbilities.defaultFor(sample);
            if(def != null)
            {
                existing.traits.add(def);
                return true;
            }
        }
        return false;
    }

    private static double round(double d)
    {
        return Math.round(d * 100D) / 100D;
    }

    private static boolean safeInvulnerable(LivingEntity e, DamageSource source)
    {
        try
        {
            return e.isInvulnerableTo(source);
        }
        catch(Throwable t)
        {
            return false;
        }
    }

    /** Variant keys for mobs we have no hand-written data for: any primitive/string NBT key that smells like a variant. */
    private static java.util.List<String> detectVariantKeys(LivingEntity e)
    {
        Set<String> keys = new LinkedHashSet<>();
        try
        {
            net.minecraft.nbt.CompoundTag tag = new net.minecraft.nbt.CompoundTag();
            e.saveWithoutId(tag);
            for(String key : tag.getAllKeys())
            {
                net.minecraft.nbt.Tag t = tag.get(key);
                if(t == null || t instanceof net.minecraft.nbt.ListTag || t instanceof net.minecraft.nbt.CompoundTag && key.equals("Brain"))
                {
                    continue;
                }
                String lower = key.toLowerCase(Locale.ROOT);
                if(lower.equals("id") || lower.equals("uuid") || lower.equals("fire") || lower.equals("air") || lower.equals("age") || lower.equals("forcedage") || lower.contains("health") || lower.contains("time") || lower.contains("cooldown"))
                {
                    continue;
                }
                for(String hint : VARIANT_HINTS)
                {
                    if(lower.contains(hint))
                    {
                        keys.add(key);
                        break;
                    }
                }
            }
        }
        catch(Throwable ignored) {}
        return new ArrayList<>(keys);
    }

    // ---- helpers for mods that don't use the vanilla movement / breathing hooks (Alex's Mobs, Naturalist, ...) ----
    private static boolean nameHas(Object o, String... parts)
    {
        if(o == null)
        {
            return false;
        }
        String n = o.getClass().getSimpleName().toLowerCase(Locale.ROOT);
        for(String p : parts)
        {
            if(n.contains(p))
            {
                return true;
            }
        }
        return false;
    }

    /** Mods can't override the final vanilla canBreatheUnderwater, so they add their own (Alex's Mobs: canBreatheUnderwaterAM). */
    private static boolean modBreathesUnderwater(LivingEntity e)
    {
        try
        {
            for(java.lang.reflect.Method m : e.getClass().getMethods())
            {
                if(m.getName().startsWith("canBreatheUnderwater") && !m.getName().equals("canBreatheUnderwater") && m.getParameterCount() == 0 && m.getReturnType() == boolean.class)
                {
                    return (Boolean)m.invoke(e);
                }
            }
        }
        catch(Throwable ignored) {}
        return false;
    }

    /** Body segments / tails / parts of multi-part mobs are LivingEntities too, but nobody should morph into one. */
    private static boolean isPart(LivingEntity e)
    {
        if("minecraft".equals(BuiltInRegistries.ENTITY_TYPE.getKey(e.getType()).getNamespace()))
        {
            return false;
        }
        String n = e.getClass().getSimpleName().toLowerCase(Locale.ROOT);
        return n.endsWith("part") || n.endsWith("segment") || n.endsWith("body") || n.endsWith("tail");
    }
}
